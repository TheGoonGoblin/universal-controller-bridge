"""Generate deterministic native UI assets from a selected icon and DejaVu font."""
from pathlib import Path
import argparse
import shutil
from PIL import Image, ImageDraw, ImageFont

p=argparse.ArgumentParser()
p.add_argument('--icon',required=True)
p.add_argument('--font',required=True)
args=p.parse_args()
root=Path(__file__).resolve().parents[1]
brand=root/'assets/brand';brand.mkdir(parents=True,exist_ok=True)
Image.open(args.icon).convert('RGB').resize((512,512),Image.Resampling.LANCZOS).save(brand/'icon0.png')
fontdir=root/'assets/fonts';fontdir.mkdir(parents=True,exist_ok=True)
target=fontdir/'DejaVuSansMono.ttf'
if Path(args.font).resolve()!=target.resolve():shutil.copyfile(args.font,target)
font=ImageFont.truetype(str(target),36)
atlas=Image.new('L',(24*64,32))
draw=ImageDraw.Draw(atlas)
for i in range(64):draw.text((24*i,-8),chr(32+i),font=font,fill=255)
mask=[]
for i in range(64):mask.extend(atlas.crop((i*24,0,i*24+24,32)).tobytes())
icon=Image.open(brand/'icon0.png').resize((96,96),Image.Resampling.LANCZOS).convert('RGB')
pixels=[0xff000000|(b<<16)|(g<<8)|r for r,g,b in icon.getdata()]
generated=root/'src/app/ui_assets.hpp'
def array(name,ctype,data):
 return f'inline constexpr {ctype} {name}[]={{\n'+''.join(','.join(str(x) for x in data[i:i+32])+',\n' for i in range(0,len(data),32))+'};\n'
generated.write_text('// Generated by tools/prepare-ui-assets.py. Font: DejaVu license; icon: UCB artwork.\n#pragma once\n#include <cstdint>\nnamespace ucb::app::assets {\n'+array('font','uint8_t',mask)+array('icon','uint32_t',pixels)+'}\n')
print('Generated icon0.png and native font/icon arrays')
